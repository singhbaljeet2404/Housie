// Small key-value layer for admin data. On Netlify it uses Netlify Blobs
// (site-wide stores, shared by every deploy); elsewhere it falls back to files
// under .data/ so local development works without any setup.

import { getStore } from "@netlify/blobs";
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";

export type StoreName = "settings" | "leads" | "media";

const blobsAvailable = () =>
  Boolean(process.env.NETLIFY_BLOBS_CONTEXT || (globalThis as { netlifyBlobsContext?: unknown }).netlifyBlobsContext);

const blobStore = (name: StoreName) => getStore({ name: `housie-${name}`, consistency: "strong" });

const DATA_DIR = join(process.cwd(), ".data");
// Keys are generated by our own code, but keep file paths inside the store dir regardless.
const filePath = (name: StoreName, key: string) => join(DATA_DIR, name, key.replace(/[^A-Za-z0-9._-]/g, "_"));

export async function getJSON<T>(name: StoreName, key: string): Promise<T | null> {
  if (blobsAvailable()) return (await blobStore(name).get(key, { type: "json" })) as T | null;
  try {
    return JSON.parse(await readFile(filePath(name, key), "utf8")) as T;
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === "ENOENT") return null;
    throw err;
  }
}

export async function setJSON(name: StoreName, key: string, value: unknown) {
  if (blobsAvailable()) {
    await blobStore(name).setJSON(key, value);
    return;
  }
  const path = filePath(name, key);
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, JSON.stringify(value, null, 2));
}

export async function getBinary(name: StoreName, key: string): Promise<{ data: ArrayBuffer; contentType: string } | null> {
  if (blobsAvailable()) {
    const result = await blobStore(name).getWithMetadata(key, { type: "arrayBuffer" });
    if (!result) return null;
    return { data: result.data, contentType: String(result.metadata.contentType ?? "application/octet-stream") };
  }
  try {
    const [data, meta] = await Promise.all([readFile(filePath(name, key)), readFile(filePath(name, `${key}.meta`), "utf8")]);
    return { data: data.buffer.slice(data.byteOffset, data.byteOffset + data.byteLength) as ArrayBuffer, contentType: JSON.parse(meta).contentType };
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === "ENOENT") return null;
    throw err;
  }
}

export async function setBinary(name: StoreName, key: string, data: ArrayBuffer, contentType: string) {
  if (blobsAvailable()) {
    await blobStore(name).set(key, data, { metadata: { contentType } });
    return;
  }
  const path = filePath(name, key);
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, Buffer.from(data));
  await writeFile(filePath(name, `${key}.meta`), JSON.stringify({ contentType }));
}

export async function listKeys(name: StoreName): Promise<string[]> {
  if (blobsAvailable()) return (await blobStore(name).list()).blobs.map((b) => b.key);
  try {
    return (await readdir(join(DATA_DIR, name))).filter((k) => !k.endsWith(".meta"));
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === "ENOENT") return [];
    throw err;
  }
}

export async function deleteKey(name: StoreName, key: string) {
  if (blobsAvailable()) {
    await blobStore(name).delete(key);
    return;
  }
  await rm(filePath(name, key), { force: true });
  await rm(filePath(name, `${key}.meta`), { force: true });
}
